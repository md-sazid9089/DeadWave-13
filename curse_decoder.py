logger = logging.getLogger(__name__)


# ── Pydantic Curse Schema ────────────────────────────────────────────────────
class CurseCase(BaseModel):
    """Structured occult case generated by the AI engine."""
    case_title: str = Field(..., description="Short evocative title for the haunted case")
    haunted_object: str = Field(..., description="The cursed item entered by the user")
    curse_description: str = Field(..., description="Supernatural affliction caused by the object")
    short_backstory: str = Field(..., description="Origins of how the curse was placed")
    puzzle_question: str = Field(..., description="The deductive question to break the curse")
    initial_clue: str = Field(..., description="First subtle clue pointing toward the answer")
    canonical_solution: str = Field(..., description="The secret 1-3 word solution")
    accepted_aliases: list[str] = Field(default_factory=list, description="Valid alternate spellings or synonyms")
    hint_1: str = Field(..., description="Progressive hint revealed after attempt 1")
    hint_2: str = Field(..., description="Direct hint revealed after attempt 2")
    success_explanation: str = Field(..., description="Atmospheric ending when the curse is broken")


# ── Deterministic Validation Utilities ───────────────────────────────────────
def normalize_answer(text: str) -> str:
    """
    Normalize text for deterministic comparison:
    - Strips leading/trailing whitespace
    - Normalizes unicode (NFKD) and strips diacritics
    - Converts to lowercase
    - Strips punctuation
    - Collapses internal whitespace
    """
    if not text:
        return ""
    # Normalize unicode decomposition
    nfkd = unicodedata.normalize("NFKD", str(text))
    without_accents = "".join([c for c in nfkd if not unicodedata.combining(c)])
    lowered = without_accents.lower().strip()
    # Strip punctuation
    stripped = re.sub(r"[^\w\s]", " ", lowered)
    # Collapse whitespace
    return " ".join(stripped.split())


def check_answer(user_input: str, canonical: str, aliases: list[str] | None = None) -> bool:
    """
    Deterministic Python answer checker.
    Compares normalized user input against normalized canonical solution and aliases.
    Does NOT do partial substring matching to prevent false positives.
    """
    norm_user = normalize_answer(user_input)
    if not norm_user:
        return False

    norm_canonical = normalize_answer(canonical)
    if norm_user == norm_canonical:
        return True

    if aliases:
        for alias in aliases:
            if norm_user == normalize_answer(alias):
                return True

    return False


def detect_solution_leakage(case: CurseCase) -> bool:
    """
    Detect if the secret canonical solution is plainly exposed in visible case fields
    (case title, description, backstory, question, or initial clue).
    """
    secret = normalize_answer(case.canonical_solution)
    if not secret:
        return True

    # Check visible text
    visible_text = f"{case.case_title} {case.curse_description} {case.short_backstory} {case.puzzle_question} {case.initial_clue}"
    norm_visible = normalize_answer(visible_text)

    # Word boundary check for secret phrase
    pattern = r"\b" + re.escape(secret) + r"\b"
    if re.search(pattern, norm_visible):
        return True

    return False


# ── AI Generation with Retries ───────────────────────────────────────────────
def generate_curse_puzzle(
    provider: AIProvider,
    haunted_object: str,
    model: str,
    max_retries: int = config.MAX_RETRIES,
) -> tuple[CurseCase | None, str | None]:
    """
    Call AI provider with structured JSON request to generate a CurseCase.
    Retries upon malformed JSON or detected solution leaks.
    """
    clean_object = haunted_object.strip()[:config.MAX_INPUT_LENGTH]
    messages = [
        {"role": "system", "content": CURSE_DECODER_SYSTEM},
        {
            "role": "user",
            "content": CURSE_DECODER_USER_TEMPLATE.format(user_input=clean_object),
        },
    ]

    last_error = ""
    for attempt in range(max_retries + 1):
        response: AIResponse = provider.generate(
            messages=messages,
            model=model,
            response_format="json",
            temperature=0.7,
        )

        if not response.success:
            last_error = response.error or "AI inference error"
            continue

        raw_content = response.content.strip()
        # Strip potential markdown fences if returned
        if raw_content.startswith("```"):
            raw_content = re.sub(r"^```(?:json)?\s*", "", raw_content)
            raw_content = re.sub(r"\s*```$", "", raw_content)

        try:
            parsed_dict = json.loads(raw_content)
            case = CurseCase.model_validate(parsed_dict)

            # Security check: check for solution leakage
            if detect_solution_leakage(case):
                logger.warning("Generated puzzle leaked solution; retrying (attempt %d)...", attempt + 1)
                last_error = "Generated puzzle revealed its own secret answer. Retrying..."
                continue

            return case, None

        except json.JSONDecodeError as jde:
            logger.warning("JSON decode error on attempt %d: %s", attempt + 1, jde)
            last_error = f"Malformed model JSON: {jde}"
        except Exception as ve:
            logger.warning("Pydantic schema validation error on attempt %d: %s", attempt + 1, ve)
            last_error = f"Invalid curse schema: {ve}"

    return None, last_error or "Failed to manifest a solvable curse puzzle after multiple attempts."


# ── State Initialization ─────────────────────────────────────────────────────
def _init_curse_state() -> None:
    """Initialize Curse Decoder game state in Streamlit."""
    if "curse_game_active" not in st.session_state:
        st.session_state.curse_game_active = False
    if "curse_case" not in st.session_state:
        st.session_state.curse_case = None
    if "curse_case_id" not in st.session_state:
        st.session_state.curse_case_id = ""
    if "curse_attempts_used" not in st.session_state:
        st.session_state.curse_attempts_used = 0
    if "curse_game_status" not in st.session_state:
        st.session_state.curse_game_status = "idle"  # idle, active, solved, failed
    if "curse_guesses" not in st.session_state:
        st.session_state.curse_guesses = []


def reset_curse_game() -> None:
    """Reset current puzzle state for a fresh investigation."""
    st.session_state.curse_game_active = False
    st.session_state.curse_case = None
    st.session_state.curse_case_id = ""
    st.session_state.curse_attempts_used = 0
    st.session_state.curse_game_status = "idle"
    st.session_state.curse_guesses = []


# ── Main UI Component ─────────────────────────────────────────────────────────
def render_curse_decoder(provider: AIProvider | None, selected_model: str) -> None:
    """
    Render the interactive Curse Decoder game card.

    Args:
        provider: Active AI provider instance or None.
        selected_model: Currently selected model string.
    """
    _init_curse_state()

    st.markdown("### 🔮 The Curse Decoder")
    st.caption("Submit a cursed relic. The Grimoire Engine constructs a solvable mystery to break its bond.")

    # ── Step 1: Object Input & Generation (When No Active Game) ───────────
    if not st.session_state.curse_game_active or st.session_state.curse_case is None:
        with st.form(key="curse_manifest_form"):
            user_relic = st.text_input(
                "Enter a haunted relic or mysterious artifact:",
                placeholder="e.g., An antique silver hand-mirror from an abandoned opera house",
                max_chars=config.MAX_INPUT_LENGTH,
                key="curse_relic_input",
            )
            manifest_btn = st.form_submit_button("⚡ Manifest Curse Case", use_container_width=True)

        # Preset idea buttons for convenience
        st.markdown("**Or inspect a cataloged relic:**")
        cols = st.columns(3)
        presets = [
            "An obsidian pocket watch frozen at 12:13 AM",
            "A weeping doll found in a flooded cellar",
            "A bloodstained music box playing in reverse",
        ]
        for idx, relic in enumerate(presets):
            with cols[idx]:
                if st.button(f"🕯️ Relic #{idx+1}", key=f"preset_btn_{idx}", use_container_width=True):
                    user_relic = relic
                    manifest_btn = True

        if manifest_btn:
            if not user_relic or not user_relic.strip():
                st.warning("You must name a cursed relic to awaken the Grimoire Engine.")
            elif not provider:
                st.error("No active AI provider connected. Select Ollama or configure Grok in the sidebar.")
            else:
                with st.spinner("░▒▓ Weaving supernatural case file from occult archives... ▓▒░"):
                    case, err = generate_curse_puzzle(
                        provider=provider,
                        haunted_object=user_relic.strip(),
                        model=selected_model,
                    )
                    if case:
                        case_id = str(uuid.uuid4())[:10]
                        st.session_state.curse_case = case
                        st.session_state.curse_case_id = case_id
                        st.session_state.curse_game_active = True
                        st.session_state.curse_attempts_used = 0
                        st.session_state.curse_game_status = "active"
                        st.session_state.curse_guesses = []

                        # Persist to database
                        try:
                            save_curse_case(
                                case_id=case_id,
                                haunted_object=case.haunted_object,
                                case_title=case.case_title,
                                status="active",
                                attempts_used=0,
                                case_data=case.model_dump(),
                            )
                        except Exception as e:
                            logger.error("Failed to save curse case to DB: %s", e)

                        st.rerun()
                    else:
                        st.error(f"🔮 Failed to manifest curse: {err}")
        return

    # ── Step 2: Active Investigation UI ──────────────────────────────────
    case: CurseCase = st.session_state.curse_case
    attempts_used = st.session_state.curse_attempts_used
    attempts_left = max(0, config.MAX_CURSE_ATTEMPTS - attempts_used)
    status = st.session_state.curse_game_status

    # Candle tracker representation
    candle_icons = ""
    for i in range(config.MAX_CURSE_ATTEMPTS):
        if i < attempts_left:
            candle_icons += "🕯️ "
        else:
            candle_icons += "💨 "

    case_html = f"""
    <div class="curse-card">
        <p class="curse-title">{case.case_title}</p>
        <p style="text-align: center; color: #ff9500; font-family: 'Share Tech Mono', monospace; font-size: 0.9rem;">
            Haunted Object: <strong>{case.haunted_object}</strong>
        </p>
        <div class="candle-tracker">
            <span>Life Candles:</span>
            <span>{candle_icons}</span>
            <span style="font-family: 'Share Tech Mono', monospace; font-size: 0.85rem; color: #fbbf24;">
                ({attempts_left}/{config.MAX_CURSE_ATTEMPTS} attempts left)
            </span>
        </div>
        <div style="margin: 0.8rem 0; font-size: 0.92rem; color: #cbd5e1; line-height: 1.5;">
            <strong>Affliction:</strong> {case.curse_description}
        </div>
        <div style="margin: 0.8rem 0; font-size: 0.88rem; color: #94a3b8; line-height: 1.4;">
            <strong>Backstory:</strong> {case.short_backstory}
        </div>
        <div class="puzzle-box">
            <p class="puzzle-question">❓ {case.puzzle_question}</p>
            <div class="clue-tag">📜 Initial Clue: {case.initial_clue}</div>
        </div>
    </div>
    """
    st.markdown(case_html, unsafe_allow_html=True)

    # ── Step 3: Progressive Hint Revelations ───────────────────────────────
    if attempts_used >= 1:
        st.info(f"💡 **First Revelation (Hint 1):** {case.hint_1}", icon="🕯️")
    if attempts_used >= 2:
        st.warning(f"⚡ **Second Revelation (Hint 2):** {case.hint_2}", icon="⚠️")

    # ── Step 4: Game Resolution States ────────────────────────────────────
    if status == "solved":
        solved_html = f"""
        <div class="curse-solved-banner">
            <h3 style="margin: 0 0 0.4rem 0; font-family: 'Cinzel', serif; letter-spacing: 2px;">
                ⚡ CURSE BROKEN ⚡
            </h3>
            <p style="margin: 0; font-size: 0.95rem;">
                {case.success_explanation}
            </p>
            <p style="margin-top: 0.5rem; font-family: 'Share Tech Mono', monospace; font-size: 0.85rem; opacity: 0.9;">
                The entity is at rest. The relic's grip dissolves into cold autumn air.
            </p>
        </div>
        """
        st.markdown(solved_html, unsafe_allow_html=True)

        if st.button("🔮 Investigate Another Relic", key="new_curse_btn_solved", use_container_width=True):
            reset_curse_game()
            st.rerun()
        return

    elif status == "failed":
        failed_html = f"""
        <div class="curse-failed-banner">
            <h3 style="margin: 0 0 0.4rem 0; font-family: 'Cinzel', serif; letter-spacing: 2px;">
                💀 STILL HAUNTED 💀
            </h3>
            <p style="margin: 0; font-size: 0.95rem;">
                All three life candles have extinguished. The curse claims another victim.
            </p>
            <div style="margin-top: 0.8rem; background: rgba(0,0,0,0.4); padding: 0.6rem 0.8rem; border-radius: 6px; font-family: 'Share Tech Mono', monospace;">
                <strong>Lost Solution:</strong> {case.canonical_solution}<br/>
                <em>{case.success_explanation}</em>
            </div>
        </div>
        """
        st.markdown(failed_html, unsafe_allow_html=True)

        if st.button("🔄 Try Another Mystery", key="new_curse_btn_failed", use_container_width=True):
            reset_curse_game()
            st.rerun()
        return

    # ── Step 5: Answer Form (Deterministic Python Grading) ────────────────
    st.markdown(render_spectral_divider("SPEAK THE COUNTER-SPELL"), unsafe_allow_html=True)

    with st.form(key=f"curse_answer_form_{st.session_state.curse_case_id}", clear_on_submit=True):
        guess = st.text_input(
            "Enter your solution to break the curse:",
            placeholder="Type your answer here...",
            max_chars=100,
        )
        col_submit, col_abandon = st.columns([3, 1])
        with col_submit:
            submit_guess = st.form_submit_button("⚡ Break Curse", use_container_width=True)
        with col_abandon:
            abandon_btn = st.form_submit_button("🏳️ Abandon", use_container_width=True)

    if abandon_btn:
        st.session_state.curse_game_status = "failed"
        st.session_state.curse_attempts_used = config.MAX_CURSE_ATTEMPTS
        try:
            update_curse_status(st.session_state.curse_case_id, "failed", config.MAX_CURSE_ATTEMPTS)
        except Exception as e:
            logger.error("Failed to update abandoned curse: %s", e)
        st.rerun()

    if submit_guess:
        if not guess or not guess.strip():
            st.warning("You must speak an answer to challenge the curse.")
        else:
            clean_guess = guess.strip()
            # Deterministic check
            is_correct = check_answer(
                user_input=clean_guess,
                canonical=case.canonical_solution,
                aliases=case.accepted_aliases,
            )

            if is_correct:
                st.session_state.curse_game_status = "solved"
                st.session_state.curse_guesses.append((clean_guess, True))
                try:
                    update_curse_status(
                        st.session_state.curse_case_id,
                        "solved",
                        st.session_state.curse_attempts_used,
                    )
                except Exception as e:
                    logger.error("Failed to update solved curse: %s", e)
                st.toast("⚡ The curse has been shattered!", icon="✨")
                st.rerun()
            else:
                st.session_state.curse_attempts_used += 1
                st.session_state.curse_guesses.append((clean_guess, False))

                if st.session_state.curse_attempts_used >= config.MAX_CURSE_ATTEMPTS:
                    st.session_state.curse_game_status = "failed"
                    try:
                        update_curse_status(
                            st.session_state.curse_case_id,
                            "failed",
                            config.MAX_CURSE_ATTEMPTS,
                        )
                    except Exception as e:
                        logger.error("Failed to update failed curse: %s", e)
                    st.toast("💀 The third candle has blown out...", icon="🕯️")
                else:
                    st.toast("❌ Incorrect counter-spell. A life candle fades...", icon="💨")
                st.rerun()

    # Show previous attempts
    if st.session_state.curse_guesses:
        st.markdown("**Investigation Log:**")
        for g_text, g_res in st.session_state.curse_guesses:
            icon = "✅" if g_res else "❌"
            st.caption(f"{icon} Attempted: *\"{g_text}\"*")
